#!/usr/bin/env python3
"""Regenerate `nautilus_mt5/` from the adapter that actually runs.

    python nautilus-mt5/sync.py ../till_infinity

## Why this script exists rather than a note asking someone to copy files

There are two copies of this adapter: `till_infinity/adapters/mt5/`, which a
live desk runs and which therefore gets every fix, and `nautilus_mt5/`, which
is the pip-installable one. **A copy maintained by hand diverges, and the
divergence is invisible from the published side.** It already happened: the
published copy sat at four modules behind and carried none of the fixes from
2026-11-01, including the one where `MarketOrderRequest.sl` has no default so
every market order was a 422 - meaning anyone who installed it got an adapter
that could not place an order, with nothing to say so.

So the copy is generated, the generated files say which commit they came from,
and a stale copy can be *seen* instead of merely suspected.

## The one transform

The source has exactly one import reaching outside its own package -
`proxy.py` wants `flag` from `till_infinity.utils.env` - and that module pulls
in a logger this package has no reason to carry. So a cut-down `env.py` is
emitted with just the three pieces `flag` needs, and the import is rewritten
to point at it. Everything else is copied byte for byte, which is what makes
`diff` between the two trees worth reading.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

#: Modules copied from the source adapter, in no particular order - the whole
#: package, so a new module appears here without this list being edited.
SOURCE = Path("till_infinity/adapters/mt5")

#: Where they land.
TARGET = Path(__file__).resolve().parent / "nautilus_mt5"

#: The imports that cannot survive the move, and what they become.
#:
#: There were two sources reaching outside the package by 2026-11-04: `proxy`
#: wants `flag`, and `data` wants `symbol_names` to check the configured
#: symbols against the instruments it just loaded. A list rather than a pair,
#: because the next one should not need this comment rewritten.
REWRITE = (
    ("from ...utils.env import flag", "from .env import flag"),
    ("from till_infinity.utils.env import symbol_names", "from .env import symbol_names"),
    ("from ...utils.env import symbol_names", "from .env import symbol_names"),
    ("from ...utils.topics import VENUE_TRADING", "from .topics import VENUE_TRADING"),
)

#: `flag`, `symbol_names` and what they need, cut out of
#: `till_infinity/utils/env.py`. Written here rather than copied because that
#: module imports a logger for the benefit of `number` and `whole`, neither of
#: which this package calls.
ENV = '''"""`flag` and `symbol_names`, cut out of `till_infinity/utils/env.py`.

**Generated by `sync.py` - do not edit.** The source module carries `number`,
`whole` and `names` too, and imports a logger for their warnings; this package
calls none of them, so carrying the logger would be a dependency for nothing.

The falsey spellings are the source's and are the point of the function: a
deployment writes `TRADING_RPYC_TUNNELLED=false` and means it, and a bare
`bool(os.environ.get(...))` reads that as true.
"""

from __future__ import annotations

import os

#: Everything that means "off". An unset variable takes the default instead.
FALSE = frozenset({"", "0", "false", "no", "off"})


def env(name: str, default: str = "") -> str:
    raw = os.environ.get(name)
    return default if raw is None else raw.strip()


def flag(name: str, default: bool = False) -> bool:
    """A setting as a switch. Unset takes the default; anything else is on
    unless it is one of `FALSE`."""
    raw = env(name)
    if not raw:
        return default
    return raw.lower() not in FALSE


def symbol_names(value: str | None) -> tuple[str, ...]:
    """Broker symbol names from one env value. **Commas win over spaces.**

    Splitting on both at once cannot express a broker symbol containing a
    space, and Deriv's synthetics all do: `"Volatility 75 Index"` became the
    three symbols `Volatility`, `75` and `Index`, so one synthetic produced
    three desks on instruments no venue lists - and nothing raised, because
    `Symbol("75")` is valid and the instrument simply never resolves.

    So a comma anywhere makes commas the only separator. Whitespace still works
    without one, and the bare-number guard catches the spelling somebody
    reaches for first.
    """
    if not value:
        return ()
    if "," in value:
        return tuple(part.strip() for part in value.split(",") if part.strip())
    found = tuple(part for part in value.split() if part)
    if any(part.isdigit() for part in found):
        raise ValueError(
            f"{value!r} splits on whitespace into {list(found)}, which contains a "
            f"bare number - so a symbol name with a space in it has been torn "
            f"apart. Separate the names with commas."
        )
    return found
'''


#: The one topic this adapter publishes, cut out of
#: `till_infinity/utils/topics.py`. Vendored for the same reason as `ENV`: that
#: module is a registry of every topic the desk declares, and this package
#: publishes exactly one of them.
TOPICS = '''"""The topic this adapter publishes on.

**Generated by `sync.py` - do not edit.** The source module is a registry of
every topic the desk declares; this package needs the one it publishes.
"""

from __future__ import annotations

#: Whether the venue will accept an order **right now**, published by the
#: execution client because it is the only component holding a bridge.
#:
#: MT5 reports `trade_allowed` twice and they are different facts: on the
#: account it is the broker's permission, on the terminal it is the AutoTrading
#: button, and an order is checked against the second. A consumer that watched
#: the account's flag would have seen `true` throughout an outage in which
#: every order came back `10027`.
VENUE_TRADING = "venue.trading"
'''


def commit(repo: Path) -> str:
    """The source commit, so a generated file can name where it came from."""
    try:
        found = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
        return found.stdout.strip() or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def header(module: str, source: str, revision: str) -> str:
    """The line that makes a stale copy visible.

    Named after the source path and commit rather than a date: a date says
    when somebody ran this, and the commit says what they ran it on, which is
    the question anyone comparing the two trees is actually asking.
    """
    return (
        f"# Generated by nautilus-mt5/sync.py from {source}/{module} at {revision}.\n"
        f"# Do not edit here - edit the source and re-run the script.\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "repo",
        type=Path,
        help="path to a till_infinity checkout",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the copy is out of date, changing nothing",
    )
    args = parser.parse_args()

    source = args.repo / SOURCE
    if not source.is_dir():
        print(f"no adapter at {source}", file=sys.stderr)
        return 2

    revision = commit(args.repo)
    wanted: dict[str, str] = {
        "env.py": header("env.py", "cut from till_infinity/utils/env.py", revision) + ENV,
        "topics.py": header("topics.py", "cut from till_infinity/utils/topics.py", revision)
        + TOPICS,
    }
    for path in sorted(source.glob("*.py")):
        text = path.read_text()
        for frm, to in REWRITE:
            text = text.replace(frm, to)
        # **Refuse rather than emit something that cannot import.** The
        # transform above handles the one import the source is known to reach
        # outside its package with. A second one would generate a module that
        # raises `ImportError` on install - and an installer has no way to
        # know this script was the thing that was wrong.
        # Both spellings: a relative `from ...utils.env` and an absolute
        # `from till_infinity.utils.env` are the same fault, and the absolute
        # one is what a module outside `adapters/` reaches for first.
        escaped = sorted(
            set(re.findall(r"^\s*from \.\.\.[\w.]+ import .*$", text, re.M))
            | set(re.findall(r"^\s*(?:from|import) till_infinity[\w.]* .*$", text, re.M))
        )
        if escaped:
            print(
                f"{path.name} reaches outside the adapter package:\n  "
                + "\n  ".join(escaped)
                + "\nAdd a transform to REWRITE, or vendor what it needs, "
                "before regenerating.",
                file=sys.stderr,
            )
            return 2
        wanted[path.name] = header(path.name, str(SOURCE), revision) + text

    # Anything in the target that the source no longer has. A module left
    # behind by a rename is a module an installer still imports.
    stale = {
        path.name
        for path in TARGET.glob("*.py")
        if path.name not in wanted and path.name != "__pycache__"
    }

    changed = sorted(
        name
        for name, text in wanted.items()
        if not (TARGET / name).exists() or _body(TARGET / name) != _body_of(text)
    )

    if args.check:
        if changed or stale:
            for name in changed:
                print(f"out of date: {name}")
            for name in sorted(stale):
                print(f"no longer in the source: {name}")
            return 1
        print(f"in sync with {revision}")
        return 0

    TARGET.mkdir(parents=True, exist_ok=True)
    for name, text in wanted.items():
        (TARGET / name).write_text(text)
    for name in sorted(stale):
        (TARGET / name).unlink()
        print(f"removed {name}, which the source no longer has")
    print(f"wrote {len(wanted)} module(s) from {revision}; {len(changed)} changed")
    return 0


def _body(path: Path) -> str:
    return _body_of(path.read_text())


def _body_of(text: str) -> str:
    """The module without its generated header.

    Compared without it so that re-running on a new commit does not report
    every file as changed when nothing in them has.
    """
    return re.sub(r"^# Generated by [^\n]*\n# Do not edit[^\n]*\n", "", text)


if __name__ == "__main__":
    raise SystemExit(main())
